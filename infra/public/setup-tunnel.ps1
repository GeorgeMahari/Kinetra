# One-time setup of the Cloudflare named tunnel for the Kinetra API.
#   powershell -ExecutionPolicy Bypass -File infra\public\setup-tunnel.ps1
#
# 1. `cloudflared tunnel login` opens the browser once: pick the domain that holds
#    KINETRA_PUBLIC_HOSTNAME. It stores %USERPROFILE%\.cloudflared\cert.pem (outside the repo).
# 2. Creates the tunnel (credentials JSON also stays in %USERPROFILE%\.cloudflared).
# 3. Points the public hostname at the tunnel (a proxied CNAME in Cloudflare DNS).
# 4. Writes the tunnel config: only /api/v1/* is forwarded, to 127.0.0.1:8000; everything else
#    gets 404 at Cloudflare's edge. PostgreSQL is never part of the tunnel.
# 5. Creates KINETRA_JWT_SECRET as a user environment variable if it does not exist yet.

. "$PSScriptRoot\common.ps1"
$s = Get-PublicSettings
$hostname = $s['KINETRA_PUBLIC_HOSTNAME']
$tunnel = $s['KINETRA_TUNNEL_NAME']
if (-not $hostname) { throw 'Set KINETRA_PUBLIC_HOSTNAME in infra\public\.env.public' }
if (-not $tunnel) { $tunnel = 'kinetra-api' }
$cf = Get-Cloudflared

if (-not (Test-Path "$env:USERPROFILE\.cloudflared\cert.pem")) {
    Write-Host 'Opening the Cloudflare login in your browser. Choose the domain of' $hostname
    & $cf tunnel login
    if ($LASTEXITCODE -ne 0) { throw 'cloudflared tunnel login failed' }
}

$existing = & $cf tunnel list --output json | ConvertFrom-Json | Where-Object { $_.name -eq $tunnel }
if (-not $existing) {
    & $cf tunnel create $tunnel
    if ($LASTEXITCODE -ne 0) { throw "cloudflared tunnel create $tunnel failed" }
    $existing = & $cf tunnel list --output json | ConvertFrom-Json | Where-Object { $_.name -eq $tunnel }
}
$id = $existing.id
$credentials = Join-Path $env:USERPROFILE ".cloudflared\$id.json"
if (-not (Test-Path $credentials)) { throw "Tunnel credentials not found: $credentials" }

& $cf tunnel route dns $tunnel $hostname
if ($LASTEXITCODE -ne 0) { Write-Warning "DNS route for $hostname was not created (it may already exist)." }

$config = @"
# Generated by infra/public/setup-tunnel.ps1. Only the API is published.
tunnel: $id
credentials-file: $credentials
no-autoupdate: true
ingress:
  - hostname: $hostname
    path: ^/api/v1/
    service: http://127.0.0.1:8000
  - service: http_status:404
"@
$configPath = Get-TunnelConfigPath $tunnel
Set-Content -Path $configPath -Value $config -Encoding utf8
& $cf tunnel --config $configPath ingress validate
if ($LASTEXITCODE -ne 0) { throw 'Tunnel ingress configuration is invalid' }

Initialize-JwtSecret

Write-Host "Tunnel '$tunnel' ($id) -> https://$hostname/api/v1/ is configured: $configPath"
